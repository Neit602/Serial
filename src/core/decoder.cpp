IncrementalTextDecoder::IncrementalTextDecoder(CharacterSet charset, bool stripHighBit)
    : m_charset(charset)
    , m_stripHighBit(stripHighBit)
{
}

void IncrementalTextDecoder::setCharset(CharacterSet charset)
{
    m_charset = charset;
    reset();
}

void IncrementalTextDecoder::reset()
{
    m_codePoint = 0;
    m_needed = 0;
    m_seen = 0;
    m_lower = 0x80;
    m_upper = 0xBF;
}

// A UTF-8 decoder with the "maximal subpart" replacement rule (Unicode §3.9,
// and what Python's "replace" handler does): an invalid or truncated
// sequence becomes exactly one U+FFFD, and the byte that broke it is decoded
// afresh.
void IncrementalTextDecoder::decodeUtf8(unsigned char byte, std::u32string &out)
{
    if (m_needed == 0) {
        if (byte < 0x80) {
            out.push_back(byte);
        } else if (byte >= 0xC2 && byte <= 0xDF) {
            m_needed = 1;
            m_codePoint = byte & 0x1F;
        } else if (byte >= 0xE0 && byte <= 0xEF) {
            m_needed = 2;
            m_codePoint = byte & 0x0F;
            if (byte == 0xE0)
                m_lower = 0xA0;
            else if (byte == 0xED)
                m_upper = 0x9F;
        } else if (byte >= 0xF0 && byte <= 0xF4) {
            m_needed = 3;
            m_codePoint = byte & 0x07;
            if (byte == 0xF0)
                m_lower = 0x90;
            else if (byte == 0xF4)
                m_upper = 0x8F;
        } else {
            out.push_back(kReplacementChar);
        }
        return;
    }
    if (byte < m_lower || byte > m_upper) {
        out.push_back(kReplacementChar);
        reset();
        decodeUtf8(byte, out);
        return;
    }
    m_lower = 0x80;
    m_upper = 0xBF;
    m_codePoint = (m_codePoint << 6) | (byte & 0x3F);
    ++m_seen;
    if (m_seen == m_needed) {
        out.push_back(m_codePoint);
        reset();
    }
}

std::u32string IncrementalTextDecoder::decode(QByteArrayView data, bool final)
{
    std::u32string out;
    out.reserve(std::size_t(data.size()));
    for (const char raw : data) {
        unsigned char byte = static_cast<unsigned char>(raw);
        if (m_stripHighBit)
            byte &= 0x7F;
        switch (m_charset) {
        case CharacterSet::Utf8:
            decodeUtf8(byte, out);
            break;
        case CharacterSet::Ascii:
            out.push_back(byte < 0x80 ? char32_t(byte) : kReplacementChar);
            break;
        case CharacterSet::Latin1:
            out.push_back(byte);
            break;
        case CharacterSet::Cp437:
            out.push_back(byte < 0x80 ? char32_t(byte) : char32_t(kCp437[byte - 0x80]));
            break;
        case CharacterSet::Cp850:
            out.push_back(byte < 0x80 ? char32_t(byte) : char32_t(kCp850[byte - 0x80]));
            break;
        }
    }
    if (final && m_needed != 0) {
        out.push_back(kReplacementChar);
        reset();
    }
    return out;
}

QString IncrementalTextDecoder::decodeToString(QByteArrayView data, bool final)
{
    return toQString(decode(data, final));
}

QString toQString(const std::u32string &text)
{
    return QString::fromUcs4(text.data(), qsizetype(text.size()));
}

